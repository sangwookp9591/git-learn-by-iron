async page => {
  const context = await page.context().browser().newContext();
  page = await context.newPage();
  const dir = '/Users/iron/orca/projects/gitlearn/src/ui/evidence/onboarding';
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const ready = () => page.waitForFunction(() => document.querySelector('#app')?.getAttribute('aria-busy') === 'false');
  const shot = async name => { await page.waitForTimeout(600); await page.screenshot({path:`${dir}/${name}.png`,fullPage:true}); };
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  const command = async text => { await page.locator('#terminal-input').fill(text); await page.locator('#terminal-input').press('Enter'); await ready(); };
  const next = async () => { await page.locator('#check-button').click(); await ready(); };
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:4177/'); await ready();
  check(await page.locator('#terminal-input').inputValue() === 'git status', 'prefilled status');
  const repoBefore = await page.evaluate(async () => { const {readProgress} = await import('/src/ui/progress.ts'); return readProgress().current; });
  check(!repoBefore, 'Run this script with a fresh browser context');
  await shot('S1-light');
  await page.locator('#terminal-input').press('Enter'); await ready();
  const timing = await page.evaluate(() => Object.fromEntries(['onboarding-first-command','onboarding-first-success'].map(n=>[n,performance.getEntriesByName(n)[0]?.startTime])));
  const status = await page.locator('#terminal-output').innerText();
  check(status.includes('❯ git status') && status.includes('현재 브랜치 main') && status.includes('.env.local'), 'Landing status must survive in workbench');
  await shot('S2-entry-light');
  await page.locator('#worktree-list .file-name').filter({hasText:'.env.local'}).click();
  await page.getByRole('button',{name:'파일 닫기'}).click();
  await command('git diff'); await next();
  check((await page.locator('#step-heading').innerText()).includes('02'),'step 2');
  await page.getByRole('button',{name:'src/payment/PaymentValidator.ts 스테이징',exact:true}).click(); await ready();
  await page.locator('#leave-button').click(); await shot('S6-returning-light');
  await page.reload();
  await page.getByRole('button',{name:'이어서 하기 · 변경 골라 담기',exact:true}).click(); await ready();
  check((await page.locator('#step-heading').innerText()).includes('02'),'resume same step');
  check((await page.locator('#staged-list').innerText()).includes('PaymentValidator.ts'),'resume same index');
  check((await page.locator('#terminal-output').innerText()).includes(status),'resume same terminal');
  await command('git stauts');
  check((await page.locator('#terminal-output').innerText()).includes('git status를 찾으시나요?'),'typo suggestion');
  await page.locator('#hint-button').click();
  await page.getByRole('button',{name:'정답 보기',exact:true}).click();
  await shot('S7-help-light');
  await command('git add src/payment/PaymentController.ts src/payment/__tests__/validator.test.ts');
  check((await page.locator('#step-heading').innerText()).includes('03'),'staging auto advances');
  await shot('S3-staged-light');
  await command('git diff --staged'); await next();
  await page.locator('#commit-message').fill('feat(payment): 카드 만료일 검증 추가\n\nRefs: PAY-231');
  await page.locator('#commit-button').click(); await ready();
  check((await page.locator('#step-heading').innerText()).includes('05'),'commit auto advances');
  await page.getByRole('button',{name:'커밋 보기 feat(payment): 카드 만료일 검증 추가',exact:true}).click();
  check((await page.locator('#file-content').innerText()).includes('PaymentValidator.ts'),'graph shows files');
  await page.getByRole('button',{name:'파일 닫기'}).click(); await next();
  await page.locator('#file-path').fill('.gitignore'); await page.getByRole('button',{name:'열기',exact:true}).click();
  const initial = await page.locator('#edit-content').inputValue();
  await page.locator('#edit-content').fill(initial+'\n.env.local\n');
  await page.getByRole('button',{name:'저장',exact:true}).click(); await ready();
  await command('git add .gitignore');
  await command('git commit -m "chore: .gitignore에 .env.local 추가" -m "Refs: PAY-231"');
  check(await page.locator('#app').getAttribute('data-screen') === 'complete','complete all 7 steps');
  await shot('S4-complete-light');
  await page.getByRole('button',{name:'나중에 하기',exact:true}).click();
  await page.locator('#theme-toggle').click(); await shot('S4-complete-dark');
  await page.locator('#catalog-button').click(); await shot('S5-catalog-dark');
  await page.setViewportSize({width:390,height:844}); await shot('S5-catalog-390');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'390px overflow');
  await page.getByRole('button',{name:'03 · 첫 티켓, 첫 브랜치',exact:true}).click(); await ready();
  await shot('S3-workbench-390-dark');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'workbench 390px overflow');
  await page.locator('#theme-toggle').click(); await shot('S3-workbench-390-light');
  check(errors.length === 0, errors.join('\n'));
  await context.close();
  return {timing,continuity:true,resume:true,completed:true,mobileOverflow:false,errors};
}
